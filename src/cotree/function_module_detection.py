import torch
from torch.utils.data import DataLoader
from kneed import  KneeLocator
import numpy as np


from cotree.DTMAE import stacked_dataset, seperate_output





def function_module_estimation(model, train_dataset, index, lambda_reg, input_size, device, 
                               learning_rate=0.01, epochs=100):
    
    """
    Estimate functional module vector for a given embedding dimension.

    Args:
        model:
            Trained autoencoder.

        train_dataset:
            Output generated by `training_dataset`. 

        index:
            Integer index of the embedding dimension to optimize the directional module
            for.

        lambda_reg:
            Regularization weight for the L1 penalty on the direction vector `f`.
            Controls sparsity; larger values encourage fewer nonzero features.

        input_size:
            Dictionary specifying the feature dimensionality of each omics layer, e.g.
            `{'G': 493, 'M': 181, 'P': 458}`. 

        device:
            Torch device to run computation on (`"cpu"` or `"cuda"`).

        learning_rate:
            Learning rate for the Adam optimizer used to update `f`. Default: 0.01.

        epochs:
            Number of optimization epochs. Default: 100.

    Returns: 
        Learned feature-direction vector.
    """


    f = torch.randn(input_size['G'] + input_size['M'] + input_size['P'], device=device)
    f = f/torch.norm(f)
    f.requires_grad_()

    dataloader = DataLoader(train_dataset, batch_size=1000, shuffle=True)
    optimizer = torch.optim.Adam([f], lr=learning_rate)

    for epoch in range(epochs):
        total_loss = 0.0
        cosine_losses = []

        for G, M, P, R, pred_target, curr_target in dataloader:
            G = G.to(device)
            M = M.to(device)
            P = P.to(device)
            R = R.to(device)
            
            N, _ = G.shape

            v = f.unsqueeze(0).expand(N, -1)  

            Z, x1_embed, x2_embed, x3_embed = model.encoder(G, M, P)

            X = torch.cat((G, M, P), dim=-1)  # shape: [N, d]
            transformed_X = X + v

            assert transformed_X.shape == X.shape, "Shape mismatch after transformation"

            G_new, M_new, P_new, _ = seperate_output(transformed_X, input_size)
            G_new = G_new.to(device)
            M_new = M_new.to(device)
            P_new = P_new.to(device)

            all_embedding, _, _, _ = model.encoder(G_new, M_new, P_new)
            f_transformed_X = all_embedding.to(Z.device)

            h = f_transformed_X - Z  # shape: [N, d_embed]

            if index >= h.shape[1]:
                raise IndexError(f"index {index} out of bounds for embedding dim {h.shape[1]}")

            numerator = h[:, index]
            denominator = torch.norm(h, dim=1) + 1e-8  # shape: [N]
            loss_terms = numerator / denominator  # shape: [N]
            cosine_loss = torch.mean(loss_terms)

            batch_loss = -cosine_loss + lambda_reg * torch.norm(f, p=1)

            optimizer.zero_grad()
            batch_loss.backward()
            optimizer.step()

            total_loss += batch_loss.item()
            cosine_losses.append(cosine_loss.item())
       
    print(f"Index {index} for functional model {index+1},"
            f"Mean Cosine: {sum(cosine_losses)/len(cosine_losses):.6f}, "
            f"Reg: {(lambda_reg * torch.norm(f, p=1)).item():.6f}")

    return f.detach().cpu().numpy()



def functional_module_species(G, M, P, v, model, index, input_size, device):

    """
    Functional module estimation.

    Args:
        G: Gene input.

        M: Metabolite input.

        P: Protein input.

        v: functional module vector.

        model:
            Trained autoencoder.

        index:
            Integer index of the embedding dimension to optimize the directional module
            for.

        input_size:
            Dictionary specifying the feature dimensionality of each omics layer, e.g.
            `{'G': 493, 'M': 181, 'P': 458}`. 

        device:
            Torch device to run computation on (`"cpu"` or `"cuda"`).

    Returns:
        selected_index (np.ndarray):
            Index of species in functional module.
    """

    def compute_loss_fn(G,M,P,v,index):
        G = G.to(device)
        M = M.to(device)
        P = P.to(device)
        v = v.to(device)
        
        N, _ = G.shape

        Z, x1_embed, x2_embed, x3_embed = model.encoder(G, M, P)

        X = torch.cat((G, M, P), dim=-1) 
        transformed_X = X + v

        G_new, M_new, P_new, _ = seperate_output(transformed_X, input_size)
        G_new = G_new.to(device)
        M_new = M_new.to(device)
        P_new = P_new.to(device)

        all_embedding, _, _, _ = model.encoder(G_new, M_new, P_new)
        f_transformed_X = all_embedding.to(Z.device)

        h = f_transformed_X - Z
        numerator = h[:, index]
        denominator = torch.norm(h, dim=1) + 1e-8
        loss_terms = numerator / denominator 
        cosine_loss = torch.mean(loss_terms)

        return -cosine_loss
    G = torch.tensor(G, device=device)
    P = torch.tensor(P, device=device)
    M = torch.tensor(M, device=device)
    species_score = np.abs(v)
    taus = np.linspace(np.min(species_score),np.max(species_score),100)
    cosine_diff = []
    selected_tau = 0
    v = torch.tensor(v, dtype=torch.float32)
    baseline_loss = compute_loss_fn(G,M,P,v,index)
    
    for tau in taus:
        new_v = v.clone()        
        idx = np.where(species_score < tau)[0]
        new_v[idx] = 0.0       
        trial_loss = compute_loss_fn(G,M,P,new_v,index)
        cosine_diff.append(trial_loss.item()-baseline_loss.item())
        if -(trial_loss.item()-baseline_loss.item())/baseline_loss.item() >= 0.1:
            break
    knee = KneeLocator(taus[:len(cosine_diff)],cosine_diff,curve="convex", interp_method="polynomial", polynomial_degree=2)
    selected_tau = knee.elbow
    if not selected_tau:
        selected_tau = taus[len(cosine_diff)-1]
    selected_index = np.where(species_score >= selected_tau)[0]
    print(f"Functional Module: {index[0]+1} Finished.")

    return selected_index



def function_score_estimation(model, index, dataset, latent_dim, para_meta, para_protein, para_dna, para_rna, keep_index, device):

    """
    Functional module score estimation.

    Args:
        model:
            Trained autoencoder.

        index:
            Integer index of the embedding dimension to optimize the directional module
            for.

        dataset: Output of OmicsDataset

        latent_dim: (dict) Dictionary specifying the latent dimension size for each omics layer, e.g.: `{'M': 30, 'P': 50, 'G': 10, 'R': 455}`.

        para_meta: Scaler of metabolite.

        para_protein: Scaler of protein.

        para_dna: Scaler of DNA.

        para_rna: Scaler of RNA.

        keep_index: (dict) Index of species included in the analysis.

        device: Torch device to run computation on (`"cpu"` or `"cuda"`).


    Returns:
        importance_score: Importance score.
    """
    
    G, M, P, R = stacked_dataset(dataset.data, para_meta, para_protein, para_dna, para_rna, keep_index) 
    eps = 1e-8  

    model.eval()
    with torch.no_grad():
        G = G.to(device)
        R = R.to(device)
        P = P.to(device)
        M = M.to(device)

        X, _, _, _, _, Z = model(G,M,P,R)

        Z[:,index] = 0

        # Predict using perturbed latent
        G_emb, M_emb, P_emb, R_emb = seperate_output(Z, latent_dim)
        G_pred, M_pred, P_pred = model.predictor(G_emb, M_emb, P_emb, R)
        X_turb = torch.cat((G_pred, M_pred, P_pred), dim=-1)

        # Normalized per-species change
        importance_score = (X_turb - X).norm(p=2, dim=0) / (X.norm(p=2, dim=0) + eps) 
    
    return importance_score.detach().cpu().numpy()  



